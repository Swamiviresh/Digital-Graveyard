function wireNavigation() {
  const path = window.location.pathname.replace(/\/$/, '') || '/';
  const activeKey = path === '/scan' ? 'scanner' : path === '/report' ? 'analysis-report' : 'home';

  document.querySelectorAll('a[data-path]').forEach((link) => {
    const key = link.dataset.path;
    link.href = ROUTES[key] || '/';
    if (link.closest('#dg-site-nav')) {
      if (key === activeKey) {
        link.setAttribute('aria-current', 'page');
        link.classList.add('nav-active');
      } else {
        link.removeAttribute('aria-current');
        link.classList.remove('nav-active');
      }
    }
  });

  // Stitch's logo/home links were exported as href="#"; make them useful.
  document.querySelectorAll('a[href="#"]').forEach((link) => {
    if (!link.dataset.path) link.href = '/';
  });

  // Normalize links generated by Stitch to our clean directory routes.
  document.querySelectorAll('a[href="/scan"], a[href="/report"]').forEach((link) => {
    link.href = link.getAttribute('href') === '/scan' ? '/scan/' : '/report/';
  });

  // Show the actual deployed origin in the minimal footer (works on custom domains too).
  document.querySelectorAll('[data-site-url]').forEach((link) => {
    link.href = window.location.origin;
    link.textContent = window.location.origin;
  });
}

function initSiteHeader() {
  const toggle = document.getElementById('dg-menu-toggle');
  const nav = document.getElementById('dg-site-nav');
  if (!toggle || !nav) return;

  const closeMenu = () => {
    nav.classList.remove('is-open');
    toggle.setAttribute('aria-expanded', 'false');
    toggle.setAttribute('aria-label', 'Open navigation');
    const icon = toggle.querySelector('.material-symbols-outlined');
    if (icon) icon.textContent = 'menu';
  };

  toggle.addEventListener('click', () => {
    const isOpen = nav.classList.toggle('is-open');
    toggle.setAttribute('aria-expanded', String(isOpen));
    toggle.setAttribute('aria-label', isOpen ? 'Close navigation' : 'Open navigation');
    const icon = toggle.querySelector('.material-symbols-outlined');
    if (icon) icon.textContent = isOpen ? 'close' : 'menu';
  });

  nav.querySelectorAll('a').forEach((link) => link.addEventListener('click', closeMenu));
  document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape') closeMenu();
  });
  document.addEventListener('click', (event) => {
    if (!nav.contains(event.target) && !toggle.contains(event.target)) closeMenu();
  });
}

function safeReadScan() {
  try {
    const value = sessionStorage.getItem('dg-current-scan');
    return value ? JSON.parse(value) : null;
  } catch {
    return null;
  }
}

function normalizeTarget(rawValue) {
  const raw = String(rawValue || '').trim();
  if (!raw) throw new Error('Enter a website URL to begin the investigation.');
  const candidate = /^https?:\/\//i.test(raw) ? raw : `https://${raw}`;
  let parsed;
  try {
    parsed = new URL(candidate);
  } catch {
    throw new Error('That URL does not look valid. Try something like https://example.com.');
  }
  if (!['http:', 'https:'].includes(parsed.protocol)) {
    throw new Error('Only HTTP and HTTPS website addresses are supported.');
  }
  if (!parsed.hostname || (!parsed.hostname.includes('.') && parsed.hostname !== 'localhost')) {
    throw new Error('Enter a complete domain name, such as example.com.');
  }
  if (parsed.username || parsed.password) {
    throw new Error('URLs containing embedded credentials are not supported.');
  }
  parsed.hash = '';
  return parsed;
}

function showInlineError(message) {
  let error = document.getElementById('scan-url-error');
  if (!error) {
    error = document.createElement('p');
    error.id = 'scan-url-error';
    error.className = 'mt-3 text-sm text-red-300';
    const container = document.getElementById('scanner-input-container');
    container?.appendChild(error);
  }
  error.textContent = message;
}

function setStageState(element, state) {
  if (!element) return;
  const icon = element.querySelector('.material-symbols-outlined');
  const badge = element.querySelector('span:last-child');
  if (state === 'active') {
    element.className = 'flex items-center justify-between p-2.5 rounded-lg bg-surface-container-high/90 text-primary font-medium transition-all shadow-[0_0_15px_rgba(183,109,255,0.15)]';
    if (icon) {
      icon.textContent = 'progress_activity';
      icon.classList.add('animate-spin');
    }
    if (badge) {
      badge.textContent = 'SIMULATING';
      badge.className = 'text-[11px] text-primary font-mono font-bold';
    }
  } else if (state === 'done') {
    element.className = 'flex items-center justify-between p-2.5 rounded-lg bg-surface-container/60 text-tertiary transition-all';
    if (icon) {
      icon.textContent = 'check_circle';
      icon.classList.remove('animate-spin');
    }
    if (badge) {
      badge.textContent = 'DONE';
      badge.className = 'text-[11px] text-tertiary font-mono font-bold';
    }
  }
}

function initScanner() {
  const form = document.getElementById('url-scanner-form');
  if (!form) return;

  const input = document.getElementById('target-url-input');
  const inputContainer = document.getElementById('scanner-input-container');
  const chamber = document.getElementById('interactive-scanning-chamber');
  const heading = document.getElementById('main-heading');
  const eyebrow = document.getElementById('eyebrow-text');
  const description = document.getElementById('main-description');
  const activeTarget = document.getElementById('active-target-url');
  const progressBar = document.getElementById('scan-progress-bar');
  const percentageText = document.getElementById('scan-percentage-text');
  const stageStatus = document.getElementById('stage-status-indicator');
  const completedAction = document.getElementById('scan-completed-action');

  window.fillTarget = (value) => {
    if (input) {
      input.value = value;
      input.focus();
    }
  };

  form.addEventListener('submit', (event) => {
    event.preventDefault();
    let target;
    try {
      target = normalizeTarget(input?.value);
    } catch (error) {
      showInlineError(error.message);
      input?.focus();
      return;
    }

    const scan = {
      url: target.href,
      hostname: target.hostname,
      submittedAt: new Date().toISOString(),
      mode: 'demo',
    };
    sessionStorage.setItem('dg-current-scan', JSON.stringify(scan));

    const error = document.getElementById('scan-url-error');
    error?.remove();
    if (inputContainer) inputContainer.classList.add('hidden');
    if (chamber) chamber.classList.remove('hidden');
    if (heading) {
      heading.innerHTML = 'Analyzing <span class="italic text-transparent bg-clip-text bg-gradient-to-r from-primary via-primary-fixed to-tertiary">Digital Footprint...</span>';
    }
    if (eyebrow) eyebrow.textContent = 'DEMO SCAN IN PROGRESS';
    if (description) description.textContent = 'Running the frontend demonstration sequence. Live certificate, domain, reputation and AI checks will be connected through the backend.';
    if (activeTarget) activeTarget.textContent = target.href;
    if (progressBar) progressBar.style.width = '0%';
    if (percentageText) percentageText.textContent = '0%';
    if (stageStatus) stageStatus.textContent = 'Starting demo sequence...';
    if (completedAction) completedAction.classList.add('hidden');

    const stages = [
      { id: 'stage-1', text: 'Preparing website target...', duration: 520 },
      { id: 'stage-2', text: 'Certificate inspection step...', duration: 580 },
      { id: 'stage-3', text: 'Domain intelligence step...', duration: 600 },
      { id: 'stage-4', text: 'Website content extraction step...', duration: 640 },
      { id: 'stage-5', text: 'Reputation lookup step...', duration: 600 },
      { id: 'stage-6', text: 'Suspicious pattern analysis step...', duration: 660 },
      { id: 'stage-7', text: 'AI assessment step...', duration: 680 },
      { id: 'stage-8', text: 'Preparing the sample report...', duration: 560 },
    ];

    let currentStep = 0;
    const runNextStage = () => {
      if (currentStep >= stages.length) {
        if (progressBar) progressBar.style.width = '100%';
        if (percentageText) percentageText.textContent = '100%';
        if (stageStatus) stageStatus.textContent = 'Demo sequence complete · Opening report';
        if (completedAction) completedAction.classList.remove('hidden');
        window.setTimeout(() => { window.location.href = '/report/'; }, 950);
        return;
      }

      const stage = stages[currentStep];
      const element = document.getElementById(stage.id);
      setStageState(element, 'active');
      if (stageStatus) stageStatus.textContent = stage.text;
      const progress = Math.round(((currentStep + 1) / stages.length) * 100);
      if (progressBar) progressBar.style.width = `${progress}%`;
      if (percentageText) percentageText.textContent = `${progress}%`;

      window.setTimeout(() => {
        setStageState(element, 'done');
        currentStep += 1;
        runNextStage();
      }, stage.duration);
    };
    runNextStage();
  });
}

function initReport() {
  const reportRoot = document.querySelector('[data-page="report"]');
  if (!reportRoot) return;

  const scan = safeReadScan();
  const displayHost = scan?.hostname || 'example.com';
  const displayUrl = scan?.url || 'https://example.com/';
  const title = document.querySelector('main h1');
  if (title) title.textContent = displayHost;

  const siteLink = document.getElementById('report-site-link');
  if (siteLink) {
    siteLink.href = displayUrl;
    siteLink.textContent = displayUrl.replace(/\/$/, '');
    siteLink.target = '_blank';
    siteLink.rel = 'noopener noreferrer';
  }
  const timestamp = document.getElementById('report-scan-timestamp');
  if (timestamp) {
    const date = scan?.submittedAt ? new Date(scan.submittedAt) : new Date();
    timestamp.textContent = `${date.toLocaleString(undefined, { dateStyle: 'medium', timeStyle: 'short' })} · DEMO`;
  }

  // Keep the page honest: this front-end currently displays fixture values.
  const notice = document.getElementById('report-demo-notice');
  if (notice && scan?.hostname) {
    const message = notice.querySelector('div');
    if (message) message.textContent = `DEMO REPORT FOR ${displayHost.toUpperCase()} · Scores and findings are sample values, not a live security assessment.`;
  }

  const showToast = (message) => {
    document.getElementById('dossierToast')?.remove();
    const toast = document.createElement('div');
    toast.id = 'dossierToast';
    toast.className = 'fixed bottom-6 right-6 z-[100] rounded-lg border border-primary/40 bg-[#292933] px-4 py-3 text-sm text-primary shadow-2xl';
    toast.textContent = message;
    document.body.appendChild(toast);
    window.setTimeout(() => toast.remove(), 2800);
  };

  const downloadButtons = [document.getElementById('pdfExportBtn'), document.getElementById('downloadPdfCta')].filter(Boolean);
  downloadButtons.forEach((button) => {
    button.addEventListener('click', () => {
      showToast('Opening your browser print dialog. Choose “Save as PDF” to export this report.');
      window.setTimeout(() => window.print(), 250);
    });
  });

  document.querySelectorAll('.accordion-trigger').forEach((trigger) => {
    trigger.addEventListener('click', () => {
      const content = trigger.nextElementSibling;
      const icon = trigger.querySelector('.accordion-icon');
      const opening = content?.classList.contains('hidden');
      content?.classList.toggle('hidden', !opening);
      icon?.classList.toggle('rotate-90', Boolean(opening));
      trigger.setAttribute('aria-expanded', String(Boolean(opening)));
    });
  });

  document.getElementById('expandAllBtn')?.addEventListener('click', () => {
    document.querySelectorAll('.accordion-content').forEach((content) => content.classList.remove('hidden'));
    document.querySelectorAll('.accordion-icon').forEach((icon) => icon.classList.add('rotate-90'));
    document.querySelectorAll('.accordion-trigger').forEach((trigger) => trigger.setAttribute('aria-expanded', 'true'));
  });

  document.getElementById('collapseAllBtn')?.addEventListener('click', () => {
    document.querySelectorAll('.accordion-content').forEach((content) => content.classList.add('hidden'));
    document.querySelectorAll('.accordion-icon').forEach((icon) => icon.classList.remove('rotate-90'));
    document.querySelectorAll('.accordion-trigger').forEach((trigger) => trigger.setAttribute('aria-expanded', 'false'));
  });
}


function initLandingScrollAnimations() {
  if (document.body.dataset.page !== 'landing') return;

  const reducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  const groups = [
    { selector: 'main > section:first-child .lg\\:col-span-6 > *', step: 85 },
    { selector: 'main > section:first-child .lg\\:col-span-6 + div', step: 0 },
    { selector: '#how-it-works > div:first-child', step: 0 },
    { selector: '#how-it-works .relative.grid > div:not(.pointer-events-none)', step: 110 },
    { selector: '#features .lg\\:col-span-5 > *', step: 75 },
    { selector: '#features .lg\\:col-span-7 > div', step: 90 },
    { selector: 'main > section:last-child .relative.rounded-3xl > *:not(.pointer-events-none)', step: 85 },
  ];

  const targets = [];
  groups.forEach(({ selector, step }) => {
    document.querySelectorAll(selector).forEach((element, index) => {
      element.classList.add('dg-scroll-reveal');
      element.style.setProperty('--dg-reveal-delay', `${Math.min(index * step, 360)}ms`);
      targets.push(element);
    });
  });

  if (reducedMotion || !('IntersectionObserver' in window)) {
    targets.forEach((element) => element.classList.add('dg-is-visible'));
    return;
  }

  const observer = new IntersectionObserver((entries, currentObserver) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      entry.target.classList.add('dg-is-visible');
      currentObserver.unobserve(entry.target);
    });
  }, {
    threshold: 0.12,
    rootMargin: '0px 0px -48px 0px',
  });

  targets.forEach((element) => observer.observe(element));
  window.addEventListener('pagehide', () => observer.disconnect(), { once: true });
}


