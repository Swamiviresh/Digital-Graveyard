function wireNavigation() {
  const path = window.location.pathname.replace(/\/$/, '') || '/';
  const activeKey = path === '/scan' ? 'scanner' : path === '/report' ? 'analysis-report' : 'home';

  document.querySelectorAll('a[data-path]').forEach((link) => {
    const key = link.dataset.path;
    link.href = ROUTES[key] || '/';
    if (link.closest('#dg-site-nav')) {
      if (key === activeKey) {
        link.setAttribute('aria-current', 'page');
        link.classList.add('nav-active');
      } else {
        link.removeAttribute('aria-current');
        link.classList.remove('nav-active');
      }
    }
  });

  // Stitch's logo/home links were exported as href="#"; make them useful.
  document.querySelectorAll('a[href="#"]').forEach((link) => {
    if (!link.dataset.path) link.href = '/';
  });

  // Normalize links generated by Stitch to our clean directory routes.
  document.querySelectorAll('a[href="/scan"], a[href="/report"]').forEach((link) => {
    link.href = link.getAttribute('href') === '/scan' ? '/scan/' : '/report/';
  });

  // Show the actual deployed origin in the minimal footer (works on custom domains too).
  document.querySelectorAll('[data-site-url]').forEach((link) => {
    link.href = window.location.origin;
    link.textContent = window.location.origin;
  });
}

function initSiteHeader() {
  const toggle = document.getElementById('dg-menu-toggle');
  const nav = document.getElementById('dg-site-nav');
  if (!toggle || !nav) return;

  const closeMenu = () => {
    nav.classList.remove('is-open');
    toggle.setAttribute('aria-expanded', 'false');
    toggle.setAttribute('aria-label', 'Open navigation');
    const icon = toggle.querySelector('.material-symbols-outlined');
    if (icon) icon.textContent = 'menu';
  };

  toggle.addEventListener('click', () => {
    const isOpen = nav.classList.toggle('is-open');
    toggle.setAttribute('aria-expanded', String(isOpen));
    toggle.setAttribute('aria-label', isOpen ? 'Close navigation' : 'Open navigation');
    const icon = toggle.querySelector('.material-symbols-outlined');
    if (icon) icon.textContent = isOpen ? 'close' : 'menu';
  });

  nav.querySelectorAll('a').forEach((link) => link.addEventListener('click', closeMenu));
  document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape') closeMenu();
  });
  document.addEventListener('click', (event) => {
    if (!nav.contains(event.target) && !toggle.contains(event.target)) closeMenu();
  });
}

